// scripts/inventory-tooltips.js
// Plan 04 — Steps 3 & 4: structured inventory of skill-badge tooltips in
// README.md and alim-ul-karim-profile.md (both walls, lines 11–17 and 92–98).
//
// Parses every line of the form:
//   <a href="HREF">[![ALT](IMG "TITLE")](LINK)</a>
// and emits one record per badge to
// .lovable/plans/subtasks/04-skill-tooltip-expanded-rewrite/inventory.json.
//
// Errors surface with file/line context; never swallowed.

import { readFileSync, writeFileSync, mkdirSync, existsSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const __dirname = dirname(fileURLToPath(import.meta.url));
const REPO_ROOT = join(__dirname, "..");
const OUT_DIR = join(
  REPO_ROOT,
  ".lovable/plans/subtasks/04-skill-tooltip-expanded-rewrite",
);
const OUT_JSON = join(OUT_DIR, "inventory.json");
const OUT_MD = join(OUT_DIR, "inventory.md");

import { readdirSync, statSync } from "node:fs";

const FILES = ["README.md", "alim-ul-karim-profile.md"];
const EXPERIENCE_DIR = "experience";

// Wrapped form used in README/profile/02-x-product.md:
//   <a href="HREF">[![ALT](IMG "TITLE")](LINK)</a>
const BADGE_WRAPPED_RE =
  /<a href="([^"]+)">\[!\[([^\]]+)\]\(([^ )]+) "([^"]+)"\)\]\(([^)]+)\)<\/a>/g;
// Bare inline form used in 009.*.md and most other experience files:
//   [![ALT](IMG "TITLE")](LINK)
const BADGE_BARE_RE =
  /\[!\[([^\]]+)\]\(([^ )]+) "([^"]+)"\)\]\(([^)]+)\)/g;

function isXproduct(rel) {
  return (
    rel.startsWith("experience/02-software-architect-x-product") ||
    rel === "experience/02-software-architect-x-product.md"
  );
}

function walkExperience(dir) {
  const out = [];
  const abs = join(REPO_ROOT, dir);
  if (!existsSync(abs)) return out;
  for (const name of readdirSync(abs)) {
    const childAbs = join(abs, name);
    const childRel = `${dir}/${name}`;
    const st = statSync(childAbs);
    if (st.isDirectory()) out.push(...walkExperience(childRel));
    else if (name.endsWith(".md")) out.push(childRel);
  }
  return out;
}

function parseLine(line) {
  // Track which character positions were already consumed by a wrapped
  // match so the bare regex doesn't double-count them.
  const consumed = [];
  const hits = [];
  for (const m of line.matchAll(BADGE_WRAPPED_RE)) {
    consumed.push([m.index, m.index + m[0].length]);
    hits.push({
      shape: "wrapped",
      col: m.index + 1,
      anchorHref: m[1],
      skill: m[2],
      img: m[3],
      title: m[4],
      linkHref: m[5],
    });
  }
  for (const m of line.matchAll(BADGE_BARE_RE)) {
    const start = m.index;
    if (consumed.some(([a, b]) => start >= a && start < b)) continue;
    hits.push({
      shape: "bare",
      col: start + 1,
      anchorHref: null,
      skill: m[1],
      img: m[2],
      title: m[3],
      linkHref: m[4],
    });
  }
  return hits;
}

function inventoryFile(rel) {
  const abs = join(REPO_ROOT, rel);
  if (!existsSync(abs)) throw new Error(`[inventory] missing file: ${rel}`);
  const src = readFileSync(abs, "utf8").split(/\r?\n/);
  const records = [];
  const xproduct = isXproduct(rel);
  src.forEach((line, idx) => {
    for (const hit of parseLine(line)) {
      records.push({
        file: rel,
        line: idx + 1,
        col: hit.col,
        shape: hit.shape,
        wall: idx + 1 <= 50 ? "top" : "bottom",
        skill: hit.skill,
        cvAnchor:
          hit.anchorHref?.replace(/^.*CV\.md#?/, "") ||
          hit.linkHref?.replace(/^.*CV\.md#?/, "") ||
          null,
        img: hit.img,
        title: hit.title,
        linkHref: hit.linkHref,
        xproduct,
      });
    }
  });
  return records;
}

function main() {
  const all = [];
  const targets = [...FILES, ...walkExperience(EXPERIENCE_DIR)];
  for (const rel of targets) {
    const recs = inventoryFile(rel);
    if (recs.length === 0) {
      console.warn(`[inventory] no badges parsed from ${rel} — regex drift?`);
    }
    all.push(...recs);
  }
  mkdirSync(OUT_DIR, { recursive: true });
  writeFileSync(OUT_JSON, JSON.stringify(all, null, 2));

  // Compact markdown summary for human review.
  const byFile = all.reduce((acc, r) => {
    (acc[r.file] ||= []).push(r);
    return acc;
  }, {});
  let md = `# Plan 04 — Step 3+4 inventory\n\nGenerated by \`scripts/inventory-tooltips.js\`. ${all.length} badges total.\n\n`;
  for (const [file, recs] of Object.entries(byFile)) {
    md += `## ${file} (${recs.length} badges)\n\n`;
    md += `| line | wall | skill | cvAnchor | current title |\n|---:|:--|:--|:--|:--|\n`;
    for (const r of recs) {
      md += `| ${r.line} | ${r.wall} | ${r.skill} | ${r.cvAnchor} | ${r.title.replace(/\|/g, "\\|")} |\n`;
    }
    md += `\n`;
  }
  writeFileSync(OUT_MD, md);

  console.log(`[inventory] wrote ${all.length} records to ${OUT_JSON}`);
  console.log(`[inventory] summary at ${OUT_MD}`);
}

try {
  main();
} catch (err) {
  console.error(`[inventory] FAILED: ${err.message}`);
  process.exitCode = 2;
}
